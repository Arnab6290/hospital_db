       COUNT(DISTINCT a.patient_id) AS patients
FROM departments dp
LEFT JOIN doctors d      ON d.dept_id = dp.dept_id
LEFT JOIN appointments a ON a.doctor_id = d.doctor_id AND a.status <> 'CANCELLED'
GROUP BY dp.dept_id, dp.name
