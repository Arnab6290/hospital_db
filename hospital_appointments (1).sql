       COUNT(a.appt_id) AS appointments
FROM doctors d
LEFT JOIN appointments a ON a.doctor_id = d.doctor_id AND a.status <> 'CANCELLED'
GROUP BY d.doctor_id, d.name
ORDER BY appointments DESC;

